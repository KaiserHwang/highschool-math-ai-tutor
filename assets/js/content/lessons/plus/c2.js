/** 점 (p, q)를 지나고 기울기 m인 직선을 그림 범위 [x0, x1]에서 그린다 */
const line = (p, q, m, x0, x1) => ({ t: 'seg', p: [x0, q + m * (x0 - p)], q: [x1, q + m * (x1 - p)] });
/** 직선 y = m x + c 의 수식(계수 1·0과 부호를 자연스럽게) */
function lineTex(m, c) {
  const mx = m === 0 ? '' : m === 1 ? 'x' : m === -1 ? '-x' : `${num(m)}x`;
  if (!mx) return `y=${num(c)}`;
  return c === 0 ? `y=${mx}` : `y=${mx}${signed(c)}`;
}

