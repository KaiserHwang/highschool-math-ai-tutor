/** x^2+bx+c=0의 근을 수식으로 */
function rootsTex(b, c) {
  const D = b * b - 4 * c;
  if (D === 0) return `x=${num(-b / 2)}\\ (\\text{중근})`;
  const s = Math.sqrt(Math.abs(D));
  if (D > 0 && Number.isInteger(s)) return `x=${num((-b - s) / 2)},\\ ${num((-b + s) / 2)}`;
  const top = `${b === 0 ? '' : num(-b)}\\pm\\sqrt{${Math.abs(D)}}${D < 0 ? '\\,i' : ''}`;
  return `x=\\dfrac{${top}}{2}`;
}

